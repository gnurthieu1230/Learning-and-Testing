## Tất cả hàm và biến của Kotlin ###

# 1. Từ khóa về BIẾN (Variables)
val = Value
var = Variable
const val = Constant Value
lateinit var = Late Initialization Variable
? = Nullable
?: = Elvis Operator
by lazy = Lazy Initialization
field = Backing Field
!! = Not-null Assertion

# 2. Từ khóa về HÀM (Functions)
fun = function
Unit = Unit
return = Return
= = Expression
infix = Infix Notation
inline = Inline Function
suspend = Suspend
vararg = Variable Arguments
crossinline = Cross-inline
noline = No-inline
tailrec = Tail Recursion
operator = Operator Overloading
get() / set() = Getter / Setter
Type.func() = Extension Function